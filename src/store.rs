use crate::DeliveryChannel;
use crate::nse::Announcement;
use anyhow::{Context, Result};
use rusqlite::{Connection, OptionalExtension, params};
use std::path::Path;

#[derive(Debug, Clone)]
pub(crate) struct PendingAnnouncement {
    pub symbol: String,
    pub seq_id: String,
    pub description: String,
    pub date: String,
    pub company_name: Option<String>,
    pub summary: Option<String>,
    pub attachment_url: Option<String>,
    pub pdf_text: Option<String>,
    pub pdf_error: Option<String>,
    pub codex_summary: Option<String>,
    pub codex_error: Option<String>,
    pub codex_attempted: bool,
    pub whatsapp_sent: bool,
    pub telegram_sent: bool,
}

/// A stored NSE announcement shown by the library and desktop widget.
#[derive(Debug, Clone)]
pub struct AnnouncementRecord {
    /// NSE symbol associated with the filing.
    pub symbol: String,
    /// NSE sequence identifier used for duplicate suppression.
    pub seq_id: String,
    /// Filing category, such as `Outcome of Board Meeting`.
    pub description: String,
    /// Date string supplied by NSE.
    pub date: String,
    /// Company name, if NSE returned one.
    pub company_name: Option<String>,
    /// Short filing summary supplied by NSE.
    pub summary: Option<String>,
    /// Original NSE attachment URL, if present.
    pub attachment_url: Option<String>,
    /// Extracted PDF text after configured clipping.
    pub pdf_text: Option<String>,
    /// Structured summary generated by Codex CLI from the extracted PDF text.
    pub codex_summary: Option<String>,
    /// Best-effort analysis error, if Codex CLI could not summarize the filing.
    pub codex_error: Option<String>,
    /// `pending`, `sent`, or `baseline`.
    pub status: String,
}

pub(crate) struct Store {
    connection: Connection,
}

impl Store {
    pub fn open(path: &Path) -> Result<Self> {
        let connection = Connection::open(path)
            .with_context(|| format!("could not open local database {}", path.display()))?;
        connection.execute_batch(
            "PRAGMA journal_mode = WAL;
             PRAGMA foreign_keys = ON;
             PRAGMA busy_timeout = 5000;
             CREATE TABLE IF NOT EXISTS tracked_symbols (
                 symbol TEXT PRIMARY KEY,
                 initialized INTEGER NOT NULL DEFAULT 0
             );
             CREATE TABLE IF NOT EXISTS announcements (
                 symbol TEXT NOT NULL,
                 seq_id TEXT NOT NULL,
                 description TEXT NOT NULL,
                 announcement_date TEXT NOT NULL,
                 company_name TEXT,
                 summary TEXT,
                 attachment_url TEXT,
                 status TEXT NOT NULL,
                 pdf_text TEXT,
                 pdf_error TEXT,
                 pdf_attempts INTEGER NOT NULL DEFAULT 0,
                 codex_summary TEXT,
                 codex_error TEXT,
                 codex_attempted INTEGER NOT NULL DEFAULT 0,
                 whatsapp_sent INTEGER NOT NULL DEFAULT 0,
                 telegram_sent INTEGER NOT NULL DEFAULT 0,
                 discovered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                 PRIMARY KEY (symbol, seq_id)
             );",
        )?;
        ensure_column(&connection, "whatsapp_sent")?;
        ensure_column(&connection, "telegram_sent")?;
        ensure_column(&connection, "codex_attempted")?;
        ensure_text_column(&connection, "codex_summary")?;
        ensure_text_column(&connection, "codex_error")?;
        Ok(Self { connection })
    }

    pub fn symbol_initialized(&self, symbol: &str) -> Result<bool> {
        let initialized = self
            .connection
            .query_row(
                "SELECT initialized FROM tracked_symbols WHERE symbol = ?1",
                [symbol],
                |row| row.get::<_, bool>(0),
            )
            .optional()?
            .unwrap_or(false);
        Ok(initialized)
    }

    pub fn record_announcements(
        &mut self,
        symbol: &str,
        announcements: &[Announcement],
        baseline: bool,
    ) -> Result<usize> {
        let status = if baseline { "baseline" } else { "pending" };
        let transaction = self.connection.transaction()?;
        let mut inserted = 0;
        {
            let mut statement = transaction.prepare(
                "INSERT OR IGNORE INTO announcements (
                    symbol, seq_id, description, announcement_date, company_name,
                    summary, attachment_url, status
                 ) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8)",
            )?;
            for announcement in announcements {
                if announcement.seq_id.trim().is_empty() {
                    continue;
                }
                if statement.execute(params![
                    symbol,
                    announcement.seq_id,
                    announcement.desc,
                    announcement.dt,
                    announcement.company_name,
                    announcement.attachment_text,
                    announcement.attachment_file,
                    status,
                ])? > 0
                {
                    inserted += 1;
                }
            }
        }
        transaction.execute(
            "INSERT INTO tracked_symbols (symbol, initialized) VALUES (?1, 1)
             ON CONFLICT(symbol) DO UPDATE SET initialized = 1",
            [symbol],
        )?;
        transaction.commit()?;
        Ok(inserted)
    }

    pub fn pending_announcements(&self) -> Result<Vec<PendingAnnouncement>> {
        let mut statement = self.connection.prepare(
            "SELECT symbol, seq_id, description, announcement_date, company_name,
                    summary, attachment_url, pdf_text, pdf_error,
                    codex_summary, codex_error, codex_attempted,
                    whatsapp_sent, telegram_sent
             FROM announcements
             WHERE status = 'pending'
             ORDER BY discovered_at ASC, symbol ASC, seq_id ASC",
        )?;
        let rows = statement.query_map([], |row| {
            Ok(PendingAnnouncement {
                symbol: row.get(0)?,
                seq_id: row.get(1)?,
                description: row.get(2)?,
                date: row.get(3)?,
                company_name: row.get(4)?,
                summary: row.get(5)?,
                attachment_url: row.get(6)?,
                pdf_text: row.get(7)?,
                pdf_error: row.get(8)?,
                codex_summary: row.get(9)?,
                codex_error: row.get(10)?,
                codex_attempted: row.get(11)?,
                whatsapp_sent: row.get(12)?,
                telegram_sent: row.get(13)?,
            })
        })?;
        rows.collect::<rusqlite::Result<Vec<_>>>()
            .context("could not read pending announcements")
    }

    pub fn recent_announcements(&self, limit: usize) -> Result<Vec<AnnouncementRecord>> {
        let mut statement = self.connection.prepare(
            "SELECT symbol, seq_id, description, announcement_date, company_name,
                    summary, attachment_url, pdf_text, codex_summary, codex_error, status
             FROM announcements
             ORDER BY discovered_at DESC, rowid DESC
             LIMIT ?1",
        )?;
        let rows = statement.query_map([limit as i64], |row| {
            Ok(AnnouncementRecord {
                symbol: row.get(0)?,
                seq_id: row.get(1)?,
                description: row.get(2)?,
                date: row.get(3)?,
                company_name: row.get(4)?,
                summary: row.get(5)?,
                attachment_url: row.get(6)?,
                pdf_text: row.get(7)?,
                codex_summary: row.get(8)?,
                codex_error: row.get(9)?,
                status: row.get(10)?,
            })
        })?;
        rows.collect::<rusqlite::Result<Vec<_>>>()
            .context("could not read recent announcements")
    }

    pub fn note_pdf_attempt(&self, symbol: &str, seq_id: &str) -> Result<u32> {
        self.connection.execute(
            "UPDATE announcements SET pdf_attempts = pdf_attempts + 1
             WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'",
            params![symbol, seq_id],
        )?;
        self.connection
            .query_row(
                "SELECT pdf_attempts FROM announcements WHERE symbol = ?1 AND seq_id = ?2",
                params![symbol, seq_id],
                |row| row.get(0),
            )
            .context("announcement disappeared while recording PDF attempt")
    }

    pub fn save_pdf_text(
        &self,
        symbol: &str,
        seq_id: &str,
        text: &str,
        error: Option<&str>,
    ) -> Result<()> {
        self.connection.execute(
            "UPDATE announcements SET pdf_text = ?3, pdf_error = ?4
             WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'",
            params![symbol, seq_id, text, error],
        )?;
        Ok(())
    }

    pub fn mark_channel_sent(
        &self,
        symbol: &str,
        seq_id: &str,
        channel: DeliveryChannel,
        require_whatsapp: bool,
        require_telegram: bool,
    ) -> Result<()> {
        let sent_column = match channel {
            DeliveryChannel::WhatsApp => "whatsapp_sent",
            DeliveryChannel::Telegram => "telegram_sent",
        };
        self.connection.execute(
            &format!(
                "UPDATE announcements SET {sent_column} = 1
                 WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'"
            ),
            params![symbol, seq_id],
        )?;

        self.connection.execute(
            "UPDATE announcements
             SET status = 'sent'
             WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'
               AND (?3 = 0 OR whatsapp_sent = 1)
               AND (?4 = 0 OR telegram_sent = 1)",
            params![symbol, seq_id, require_whatsapp, require_telegram],
        )?;
        Ok(())
    }

    pub fn save_pdf_error(&self, symbol: &str, seq_id: &str, error: &str) -> Result<()> {
        self.connection.execute(
            "UPDATE announcements SET pdf_error = ?3
             WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'",
            params![symbol, seq_id, error],
        )?;
        Ok(())
    }

    pub fn save_codex_analysis(
        &self,
        symbol: &str,
        seq_id: &str,
        summary: Option<&str>,
        error: Option<&str>,
    ) -> Result<()> {
        self.connection.execute(
            "UPDATE announcements
             SET codex_summary = ?3, codex_error = ?4, codex_attempted = 1
             WHERE symbol = ?1 AND seq_id = ?2 AND status = 'pending'",
            params![symbol, seq_id, summary, error],
        )?;
        Ok(())
    }

    pub fn codex_analysis_attempted(&self, symbol: &str, seq_id: &str) -> Result<bool> {
        self.connection
            .query_row(
                "SELECT codex_attempted FROM announcements WHERE symbol = ?1 AND seq_id = ?2",
                params![symbol, seq_id],
                |row| row.get(0),
            )
            .optional()
            .map(|attempted| attempted.unwrap_or(false))
            .context("could not read Codex analysis state")
    }

    pub fn pending_count(&self) -> Result<usize> {
        self.connection
            .query_row(
                "SELECT COUNT(*) FROM announcements WHERE status = 'pending'",
                [],
                |row| row.get::<_, i64>(0),
            )
            .map(|count| count.max(0) as usize)
            .context("could not count pending announcements")
    }
}

fn ensure_column(connection: &Connection, column: &str) -> Result<()> {
    let exists = connection.query_row(
        "SELECT EXISTS(
             SELECT 1 FROM pragma_table_info('announcements') WHERE name = ?1
         )",
        [column],
        |row| row.get::<_, bool>(0),
    )?;
    if !exists {
        connection.execute_batch(&format!(
            "ALTER TABLE announcements ADD COLUMN {column} INTEGER NOT NULL DEFAULT 0;"
        ))?;
    }
    Ok(())
}

fn ensure_text_column(connection: &Connection, column: &str) -> Result<()> {
    let exists = connection.query_row(
        "SELECT EXISTS(
             SELECT 1 FROM pragma_table_info('announcements') WHERE name = ?1
         )",
        [column],
        |row| row.get::<_, bool>(0),
    )?;
    if !exists {
        connection.execute_batch(&format!(
            "ALTER TABLE announcements ADD COLUMN {column} TEXT;"
        ))?;
    }
    Ok(())
}
